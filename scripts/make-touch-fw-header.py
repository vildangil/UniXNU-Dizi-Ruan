#!/usr/bin/env python3
"""Generate .cache/hakios-fw/hakios.novatek_ruan_fw.h from the stock NT36532 touch firmware (vendor firmware, not in git).

  adb pull /vendor/firmware/novatek_ts_fw_boe.bin
  python3 scripts/make-touch-fw-header.py novatek_ts_fw_boe.bin

package/hakios.novatek_ruan.h (the ruan port's HakiOS NT36532 driver) uploads it to the touch controller with ruan_touch=1.
"""
import hashlib
import sys
from pathlib import Path

if len(sys.argv) != 2:
    raise SystemExit(__doc__)
data = Path(sys.argv[1]).read_bytes()
if not 0x1000 <= len(data) <= 0x100000:
    raise SystemExit(f'{sys.argv[1]}: {len(data)} bytes does not look like NT36532 firmware')
out = Path(__file__).resolve().parents[1] / '.cache/hakios-fw/hakios.novatek_ruan_fw.h'
out.parent.mkdir(parents=True, exist_ok=True)
rows = ',\n'.join('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16))
out.write_text(f'/* Generated by scripts/make-touch-fw-header.py from {Path(sys.argv[1]).name}, sha256 '
               f'{hashlib.sha256(data).hexdigest()}. Vendor firmware: do not commit. */\n#pragma once\n'
               f'#define NOVATEK_RUAN_FW_LENGTH {len(data)}u\n'
               f'static const unsigned char novatek_ruan_fw[{len(data)}] = {{\n{rows}\n}};\n')
print(f'{out}: {len(data)} bytes')
